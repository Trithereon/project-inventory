CREATE TABLE IF NOT EXISTS pantheons (
  id INTEGER PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  name VARCHAR(100) NOT NULL UNIQUE,
  origin VARCHAR(100) NOT NULL,
  description VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS gods (
  id INTEGER PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  pantheon_id INTEGER NOT NULL,
  name VARCHAR(100) NOT NULL,
  gender VARCHAR(13),
  description VARCHAR(500),
  status VARCHAR(5),
  img_url TEXT
);

CREATE TABLE IF NOT EXISTS domains (
  id INTEGER PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS symbols (
  id INTEGER PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  symbol VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS god_symbols (
  god_id INTEGER NOT NULL,
  symbol_id INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS god_domains (
  god_id INTEGER NOT NULL,
  domain_id INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS god_counterparts (
  god_a_id INTEGER NOT NULL,
  god_b_id INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS god_parents (
  parent_id INTEGER NOT NULL,
  child_id INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS god_peers (
  god_a_id INTEGER NOT NULL,
  god_b_id INTEGER NOT NULL,
  relation VARCHAR(100)
);
